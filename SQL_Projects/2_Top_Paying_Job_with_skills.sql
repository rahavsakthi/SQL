/*
    What skills are required for the top-paying data analyst jobs?
    Figuring out top 10 highest-paying Data Analyst jobs
    Add the specific skills required for those roles
    Why? It provides a detailed look at which high-paying jobs demand certain skills,
    to understand which skills to develop that align with top salaries
*/

WITH top_job AS (

SELECT
    job_id,
    job_title,
    company_dim.name AS company_name,
    salary_year_avg

FROM
    job_postings_fact 

LEFT JOIN company_dim
    ON job_postings_fact.company_id = company_dim.company_id

WHERE
    job_title_short = 'Data Analyst' AND 
    job_location = 'Anywhere' AND
    salary_year_avg IS NOT NULL

ORDER BY
    salary_year_avg DESC

LIMIT 10
)

SELECT
    top_job.*,
    skills

FROM top_job

INNER JOIN skills_job_dim ON top_job.job_id = skills_job_dim.job_id
INNER JOIN skills_dim ON skills_dim.skill_id =skills_job_dim.skill_id

